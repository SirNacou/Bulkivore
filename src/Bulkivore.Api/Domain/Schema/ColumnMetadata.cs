using Vogen;

namespace Bulkivore.Api.Domain.Schema;

[ValueObject<(string, ColumnDataType, bool, int?, bool)>]
public readonly partial struct ColumnMetadata
{
    public string Name => Value.Item1;
    public ColumnDataType DataType => Value.Item2;
    public bool IsNullable => Value.Item3;
    public int? MaxLength => Value.Item4;
    public bool IsAutoGenerated => Value.Item5;

    public static ErrorOr<ColumnMetadata> Create(string name, ColumnDataType dataType, bool isNullable, int? length,
        bool isAutoGenerated)
    {
        var result = TryFrom((name, dataType, isNullable, length, isAutoGenerated));
        if (result.IsSuccess)
            return result.ValueObject;
        return Error.Validation(description: result.Error.ErrorMessage);
    }

    private static Validation Validate((string, ColumnDataType, bool, int?, bool) input)
    {
        bool isValid = !string.IsNullOrWhiteSpace(input.Item1);
        return isValid ? Validation.Ok : Validation.Invalid("Column name cannot be empty");
    }

    private static (string, ColumnDataType, bool, int?, bool) NormalizeInput(
        (string, ColumnDataType, bool, int?, bool) input)
    {
        input.Item1 = input.Item1.Trim();
        input.Item4 = input.Item4 > 0 ? input.Item4 : null;
        return input;
    }
}
